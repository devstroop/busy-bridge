# Migrates the legacy BUSY Integration documents (Word/Excel) to Markdown
# under docs/archive/, preserving original base names. .doc is converted via
# LibreOffice first, then everything goes through pandoc; .xls goes through
# pandas (scripts/docs/xls_to_md.py). Output is committed so the archive is
# reproducible without the original documents.
#
# Usage: powershell -File scripts/docs/extract.ps1 [-Source <path>]
param(
    [string]$Source = (Join-Path $PSScriptRoot '..\..\..\BUSY Integration'),
    [string]$OutDir = (Join-Path $PSScriptRoot '..\..\docs\archive')
)
$ErrorActionPreference = 'Stop'
[Console]::OutputEncoding = [Text.Encoding]::UTF8

if (-not (Test-Path $Source)) { throw "source not found: $Source" }
New-Item -ItemType Directory -Force -Path $OutDir | Out-Null

# tool discovery
$pandoc = (Get-Command pandoc -ErrorAction SilentlyContinue).Source
if (-not $pandoc) {
    $pandoc = @("$env:LOCALAPPDATA\Microsoft\WinGet\Links\pandoc.exe",
                'C:\Program Files\Pandoc\pandoc.exe') |
        Where-Object { Test-Path $_ } | Select-Object -First 1
}
if (-not $pandoc) { throw 'pandoc not found' }
$soffice = 'C:\Program Files\LibreOffice\program\soffice.exe'
if (-not (Test-Path $soffice)) { throw 'LibreOffice not found' }
$py = (Get-Command python -ErrorAction SilentlyContinue).Source
if (-not $py) { throw 'python not found' }

$docs = @(Get-ChildItem $Source -Recurse -Include *.doc, *.docx, *.xls)
$xls  = @($docs | Where-Object Extension -eq '.xls')
$word = @($docs | Where-Object { $_.Extension -in '.doc', '.docx' })

# .doc -> .docx via LibreOffice (batch into a temp dir)
$tmp = Join-Path $env:TEMP 'busy-doc-extract'
Remove-Item $tmp -Recurse -Force -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Force -Path $tmp | Out-Null
$legacy = @($word | Where-Object Extension -eq '.doc')
if ($legacy.Count -gt 0) {
    & $soffice --headless --norestore --convert-to docx --outdir $tmp @($legacy.FullName) | Out-Null
    # soffice returns before finishing; wait for every expected twin
    $deadline = (Get-Date).AddSeconds(60)
    do {
        Start-Sleep -Milliseconds 500
        $missing = @($legacy | Where-Object { -not (Test-Path (Join-Path $tmp ($_.BaseName + '.docx'))) })
    } while ($missing.Count -gt 0 -and (Get-Date) -lt $deadline)
    if ($missing.Count -gt 0) { throw "LibreOffice conversion timed out: $($missing.Name -join ', ')" }
}

$converted = @{}
foreach ($f in Get-ChildItem $tmp -Filter *.docx) { $converted[$f.BaseName] = $f.FullName }
# legacy .doc resolves to its converted twin by base name; .docx uses itself
$plan = @()
foreach ($f in $word) {
    if ($f.Extension -eq '.docx') { $plan += @{ src = $f.FullName; base = $f.BaseName } }
    else {
        $t = $converted[$f.BaseName]
        if (-not $t) { Write-Warning "conversion failed: $($f.Name)"; continue }
        $plan += @{ src = $t; base = $f.BaseName }
    }
}

$manifest = @("# Document extraction manifest", "",
    "Generated by `scripts/docs/extract.ps1` from the original BUSY Integration",
    "documents (Word/Excel, 2017-era). Do not edit archive files by hand.", "",
    "| Output | Source | Tool |", "|---|---|---|")

foreach ($p in $plan) {
    $mdName = "$($p.base).md"
    & $pandoc -f docx -t gfm --wrap=none -o (Join-Path $OutDir $mdName) $p.src
    if ($LASTEXITCODE -ne 0) { throw "pandoc failed: $($p.src)" }
    $manifest += "| docs/archive/$mdName | $(Split-Path $p.src -Leaf) | pandoc |"
    Write-Output "OK docx -> $mdName"
}
foreach ($x in $xls) {
    $mdName = "$($x.BaseName).md"
    & $py (Join-Path $PSScriptRoot 'xls_to_md.py') $x.FullName (Join-Path $OutDir $mdName)
    if ($LASTEXITCODE -ne 0) { throw "xls conversion failed: $($x.Name)" }
    $manifest += "| docs/archive/$mdName | $($x.Name) | pandas |"
    Write-Output "OK xls  -> $mdName"
}
$manifest | Out-File -Encoding utf8 (Join-Path $OutDir 'MANIFEST.md')
Write-Output "extracted $($plan.Count + $xls.Count) documents -> $OutDir"
